"""Текстовая гигиена: три класса дефектов в русских строках отчётов.

Зачем этот файл вообще существует. Слайс 1.31.0 поймал три СОБСТВЕННЫХ
дефекта, которые не ловит ни компилятор, ни тесты продукта:

  * латиница, прилиплая к кириллице в комментарии теста (код + igl);
  * то же самое в docstring продукта (du + эта);
  * пропущенный пробел у кавычки в CHANGELOG (ОК + читается без пробела).

Каждый из них портит ровно ту строку, которую оператор читает в момент
аварии, то есть принадлежит тому же классу, что и весь остальной слайс:
отчёт врёт не смыслом, а оформлением. Лечится класс, а не три случая.

ДВА контроля, и второй важнее первого. Позитивный (детектор обязан видеть
приманку) без негативного бесполезен: первый черновой вариант проверял любую
кавычку и дал 98 ЛОЖНЫХ срабатываний на концах строковых литералов Python и
на кавычках в README — в таком шуме единственная настоящая находка тонет.
Поэтому фиксированы оба списка.
"""
import pathlib
import re

# Иероглифы, затесавшиеся в русский текст (клавиатурная опечатка другого
# языка). В исходнике здесь escape-последовательности, а не сами символы,
# поэтому скан этого файла их не находит.
CJK_DEFECT = re.compile('[\u3000-\u9fff\uf900-\ufaff\uff00-\uffef]')

# Латиница, прилиплая к кириллице, в обе стороны.
LETTER_GLUE = re.compile('[A-Za-z]{2,}[а-яёА-ЯЁ]|[а-яёА-ЯЁ][A-Za-z]{2,}')

# Пропущенный пробел у «ёлочки» — в обе стороны. ONLY «ёлочки»: ASCII-кавычка
# невозможно легитимно оканывает строковый литерал Python и встречается в
# markdown, включая её нельзя (замерено: 98 ложных срабатываний против 2
# настоящих).
QUOTE_GLUE = re.compile('»[а-яёА-ЯЁ]|[а-яёА-ЯЁ]«')

DETECTORS = (('CJK', CJK_DEFECT),
             ('СКЛЕЙКА-БУКВЫ', LETTER_GLUE),
             ('СКЛЕЙКА-ЁЛОЧКА', QUOTE_GLUE))

# Что сканируем: продукт, его тесты и два документа, где оператор читает
# обещания и инструкции.
#
# Список расширен в 1.32.0 файлами этого слайса. Расширение разрешено только
# после замера ложных срабатываний: полный проход по всем *.py, tests/*.py и
# четырём документам (61 файл) дал НОЛЬ нарушений, поэтому расширение не
# тонет в шуме. Смысл ровно тот же, из-за чего существует файл: дефект ловится
# в ту секунду, когда он написан, а не когда оператор увидел строку в отчёте.
# В 1.32.0 сторож поймал три таких дефекта в МОИХ же свежих docstring
# (склейки латиницы с кириллицей) - то есть работает.
# В 1.32.1 добавлен tests/test_git_history.py: в его первом же черновике
# оказались иероглифы (тот самый класс, что ловит CJK-детектор) и латинское
# слово в русском комментарии. Guard, который проверяет чужие тексты, обязан
# сам стоять под тем же сканом, иначе он написан вслепую.
#
# В 1.32.4 добавлены четыре файла BitrixVM: этот слайс писал в них тексты,
# которые читает оператор, а под сканом они не стояли — то есть сторож молчал ровно там, где
# дефект мог быть написан. Расширение разрешено только после замера: ad-hoc
# проход по всем четырём дал НОЛЬ нарушений, поэтому список не тонет в шуме.
HYGIENE_FILES = ('panels.py', 'common.py', 'logs.py', 'bitrix.py',
                 'gui_bitrix.py',
                 'tests/test_panels.py', 'tests/support.py',
                 'tests/test_common.py', 'tests/test_logs.py',
                 'tests/test_bitrix.py', 'tests/test_gui_bitrix.py',
                 'tests/test_text_hygiene.py', 'tests/test_git_history.py',
                 'CHANGELOG.md', 'README.md')

# Приманки собраны из кусков ('код' + 'igl'), иначе этот файл находил бы
# СОБСТВЕННЫЙ текст приманки при скане и горел бы вечно.
POSITIVE_TRAPS = {
    'код' + 'igl': 'СКЛЕЙКА-БУКВЫ',
    'du' + 'эта': 'СКЛЕЙКА-БУКВЫ',
    '«ОК»' + 'читается': 'СКЛЕЙКА-ЁЛОЧКА',
    'он сказал' + '«продолжай»': 'СКЛЕЙКА-ЁЛОЧКА',
    'текст ' + chr(0x4e86) + ' текст': 'CJK',
}

# Легитимные конструкции, которые широкий детектор считал дефектами. Если хоть
# одна поймается — детектор непригоден, а не строка.
NEGATIVE_SAMPLES = (
    'lines.append("✅ Панель работает" if rc == 0 else x)',
    '- Кнопка "Подключиться" меняется на "Отключиться"',
    'честного «не видно». Теперь при пустом ответе — "не проверено", а не',
    '"истёк".',
    'f"это «не проверено», а не "',
    'hostname «srv123» без точки',
    "LC_ALL=C dpkg -l 'fastpanel2*' 2>&1",
    '"""Управление панелями: ISPmanager (mgrctl) и FastPanel."""',
)


def _text_defects(line):
    """Видимые текстовые дефекты строки: [(класс, фрагмент), ...]."""
    found = []
    for kind, rx in DETECTORS:
        match = rx.search(line)
        if match:
            found.append((kind, match.group(0)))
    return found


class TestTextHygiene:
    def test_detectors_see_their_own_traps(self):
        # ПЕРВЫМ делом — контрпример. Ноль нарушений в стороже без него
        # неотличим от слепого детектора (урок серии: guard обязан измерять
        # ВИДИМОСТЬ детектора, а не пустой результат). Черновой QUOTE-детектор
        # был слеп к пробелу ДО открывающей кавычки — контрпример поймал это
        # ещё до запуска pytest.
        for trap, want in POSITIVE_TRAPS.items():
            kinds = [k for k, _ in _text_defects(trap)]
            assert want in kinds, 'ДЕТЕКТОР СЛЕПОЙ к %r: вижу %s' % (trap, kinds)

    def test_detectors_ignore_legitimate_text(self):
        # Обратная сторона того же закона: детектор, который ловит синтаксис
        # Python и кавычки markdown, обесценивает настоящие находки.
        for sample in NEGATIVE_SAMPLES:
            hits = _text_defects(sample)
            assert not hits, 'ДЕТЕКТОР ГЛОХНЕТ (ложное %s): %r' % (hits, sample)

    def test_series_files_have_no_text_defects(self):
        root = pathlib.Path(__file__).resolve().parents[1]
        bad = []
        for rel in HYGIENE_FILES:
            path = root / rel
            assert path.exists(), 'скан молчит: файла нет — %s' % rel
            for n, line in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
                for kind, frag in _text_defects(line):
                    bad.append('%s:%d [%s %r] %s' % (rel, n, kind, frag,
                                                     line.strip()[:88]))
        assert not bad, 'текстовых дефектов: %d\n  %s' % (
            len(bad), '\n  '.join(bad[:12]))

    def test_scan_actually_scans(self):
        # Инвертированный контроль самого сканера: проверка «в файлах чисто»
        # тривиально проходит, если список файлов пуст или путь мимо. Замеряем,
        # что скан реально видит содержимое.
        root = pathlib.Path(__file__).resolve().parents[1]
        seen = 0
        for rel in HYGIENE_FILES:
            text = (root / rel).read_text(encoding='utf-8')
            assert text.strip(), 'пустой файл в списке скана: %s' % rel
            seen += len(text.splitlines())
        assert seen > 3000, 'скан деградировал: строк %d' % seen
